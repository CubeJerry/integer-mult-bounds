#!/usr/bin/env python3
"""On-demand small-field repair replay; predecessor orbit operators credited."""
from itertools import product
from math import comb, isqrt
from pathlib import Path
import hashlib
import importlib.util
import json
import numpy as np

SOURCE=Path(__file__).resolve().parents[3]/'routes/B/verify_order_three_interchange.py'
spec=importlib.util.spec_from_file_location('source_orbits',SOURCE)
old=importlib.util.module_from_spec(spec)
spec.loader.exec_module(old)
MUL, INV, POW3 = old.MUL, old.INV, old.POW3


def inverse(matrix):
    n=len(matrix)
    out=np.concatenate((matrix.copy(),np.eye(n,dtype=np.uint8)),axis=1)
    for j in range(n):
        pivot=next(i for i in range(j,n) if out[i,j])
        out[[j,pivot]]=out[[pivot,j]]
        out[j]=MUL[INV[out[j,j]],out[j]]
        for i in range(n):
            if i != j and out[i,j]:
                out[i]^=MUL[out[i,j],out[j]]
    assert np.array_equal(out[:,:n],np.eye(n,dtype=np.uint8))
    return out[:,n:]


def projective_shifts(m):
    r,B=1,3
    while (B-1)//2<m: r,B=r+1,3*B
    directions=[a for a in product(range(3),repeat=r)
                if next((v for v in a if v),0)==1]
    basis=[tuple(int(i==j) for i in range(r)) for j in range(r)]
    chosen=(basis+[a for a in directions if a not in basis])[:m]
    return np.array([[sum(a*b for a,b in zip(seed,v))%3 for v in chosen]
                     for seed in product(range(3),repeat=r)],dtype=np.int64)


def scalar_data(key,shifts,u,T):
    counts=np.sum((shifts+np.asarray(key))%3,axis=1)
    z=int(POW3[int(sum(key))%3])
    p=POW3[(u-np.sum(shifts,axis=1)+(counts-u)%T)%3]
    J=np.flatnonzero((counts<u)|(counts>=u+T))
    return z,p,J


def on_demand_table(z,p,J,s,fault=''):
    j=len(J)
    assert j<=s
    out=np.zeros((s,s),dtype=np.uint8)
    if not j: return out
    V=np.array([[old.fpow(int(node),h) for node in J] for h in range(j)],dtype=np.uint8)
    Vi=inverse(V)
    gaps=p[J]^z
    diagonal=np.ones(j,dtype=np.uint8) if fault=='omit_gap_square' else MUL[gaps,gaps]
    left=Vi if fault=='omit_transpose' else Vi.T
    out[:j,:j]=old.matmul(MUL[left,diagonal[None,:]],Vi)
    return out


counts={'physical_repair_cases':0,'parent_scalar_outputs':0,
        'negative_offset_predictor_cases':0,'pairwise_count_cases':0,
        'zero_gap_containing_set_cases':0,'phase_ledger_cases':0}
negatives={}
rng=np.random.default_rng(130026)

# Reuse only the predecessor's direct physical orbit/converter implementation.
# New shifts, predictor values, per-address inverses and packed module repair
# are generated by this checker.
shifts=projective_shifts(3)
B=len(shifts); MODULE=2; N=old.N; u,T=2,4
assert B==9
keys={sign:(sign*old.K)%3 for sign in (1,-1)}
data={sign:[scalar_data(keys[sign][:,f],shifts,u,T) for f in range(N)]
      for sign in (1,-1)}
s=max(len(J) for cases in data.values() for z,p,J in cases)
S=s*MODULE+2                 # nontrivial paid zero padding in the finite toy
H=np.array([[old.fpow(node,h) for node in range(B)] for h in range(s)],dtype=np.uint8)


def predictor(x,sign):
    diagonal=np.array([case[1] for case in data[sign]],dtype=np.uint8).T
    spectral=old.direct_converter(x.reshape(B*MODULE,N)).reshape(B,MODULE,N)
    return old.direct_converter(MUL[diagonal[:,None,:],spectral].reshape(-1,N),inverse=True).reshape(B,MODULE,N)


def checks(x):
    out=np.zeros((S,N),dtype=np.uint8)
    for module in range(MODULE):
        out[np.arange(s)*MODULE+module]=old.matmul(H,x[:,module,:])
    return out


def lift(x,wrong_module=False):
    out=np.zeros((B,MODULE,N),dtype=np.uint8)
    for module in range(MODULE):
        source=(module+1)%MODULE if wrong_module else module
        out[:,module,:]=old.matmul(H.T,x[np.arange(s)*MODULE+source])
    return out


def repair(x,sign,fault=''):
    px=predictor(x,sign)
    spectral=old.direct_converter(np.concatenate((checks(px),checks(x))))
    if fault=='incomplete_forward': spectral=np.concatenate((checks(px),checks(x)))
    transformed=np.zeros_like(spectral)
    for f in range(N):
        z,p,J=data[sign if fault!='wrong_inverse_key' else 1][f]
        matrix=on_demand_table(z,p,J,s,fault)
        for module in range(MODULE):
            rows=np.arange(s)*MODULE+module
            discrepancy=spectral[rows,f]^MUL[z,spectral[S+rows,f]]
            a=old.matmul(matrix,discrepancy[:,None])[:,0]
            transformed[rows,f]=a
            transformed[S+rows,f]=MUL[z,a]
    assert not np.any(transformed[s*MODULE:S])
    assert not np.any(transformed[S+s*MODULE:])
    ordinary=old.direct_converter(transformed,inverse=True)
    z=lift(ordinary[:S],fault=='wrong_module')
    fz=lift(ordinary[S:])
    return px^predictor(z,sign)^fz


for sign in (1,-1):
    for label in range(3):
        x=rng.integers(0,256,size=(B,MODULE,N),dtype=np.uint8)
        target=old.direct(x.reshape(-1,N),sign).reshape(x.shape)
        assert np.array_equal(repair(x,sign),target)
        counts['physical_repair_cases']+=1
        counts['parent_scalar_outputs']+=x.size
    for fault in ('omit_gap_square','omit_transpose','incomplete_forward','wrong_module'):
        mismatch=int(np.count_nonzero(repair(x,sign,fault)!=target))
        negatives[f'{fault}_{sign}']=mismatch
        assert mismatch>0
    if sign==-1:
        mismatch=int(np.count_nonzero(repair(x,sign,'wrong_inverse_key')!=target))
        negatives['wrong_inverse_key']=mismatch
        assert mismatch>0

for z in POW3:
    J=np.array([0,2,4],dtype=np.int64)
    p=np.full(5,z,dtype=np.uint8)
    p[2]^=int(POW3[1]); p[4]^=1
    check=np.array([[old.fpow(node,h) for node in range(5)] for h in range(3)],dtype=np.uint8)
    matrix=on_demand_table(int(z),p,J,3)
    x=rng.integers(0,256,size=(5,7),dtype=np.uint8)
    px=MUL[p[:,None],x]
    error=old.matmul(check,px)^MUL[z,old.matmul(check,x)]
    correction=old.matmul(check.T,old.matmul(matrix,error))
    assert np.array_equal(px^MUL[p[:,None],correction]^MUL[z,correction],MUL[z,x])
    counts['zero_gap_containing_set_cases']+=1

for m,u0,T0 in [(3,2,4),(121,58,128)]:
    for c in range(2*m+1):
        a=c-u0
        value=0
        for h in range(T0):
            coefficient=(comb(a,h) if 0<=h<=a else 0) if a>=0 else comb(h-a-1,h)
            if coefficient&1: value^=int(POW3[(2*h)%3])
        value=int(MUL[POW3[u0%3],value])
        assert value==int(POW3[(u0+(c-u0)%T0)%3])
        counts['negative_offset_predictor_cases']+=1

for m in (2,3,4):
    family=projective_shifts(m)
    for key in product(range(3),repeat=m):
        c=np.sum((family+key)%3,axis=1)
        assert int(np.sum(c))==m*len(family)
        assert 3*int(np.sum((c-m)**2))==2*m*len(family)
        counts['pairwise_count_cases']+=1

for m in [4096,4097,5000,8192,16384,65536,10**6]:
    batch=3
    while (batch-1)//2<m: batch*=3
    b0=5*(isqrt(m)+(isqrt(m)**2<m))
    length=1
    while length<2*b0+1: length*=2
    assert length-1<=m
    s0=batch//32
    assert 75*s0>=2*batch
    for w in [1,2,32,1<<100]:
        parent=batch*32*w; phase_half=parent//32
        assert phase_half==batch*w and 16*(2*phase_half)==parent
        assert s0*32*w<=phase_half
        assert phase_half-s0*32*w==(batch-32*s0)*w
        assert 16*(2*batch)==32*batch
        counts['phase_ledger_cases']+=1

result={
    'status':'passed',
    'arithmetic':'exact finite-field arithmetic in F256 with F4 subfield',
    'source_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    'predecessor_orbit_source':str(SOURCE.relative_to(Path(__file__).resolve().parents[3])),
    'predecessor_orbit_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
    'counts':counts,
    'negative_controls':negatives,
    'toy':{'m':3,'shifts':9,'module_width':MODULE,'physical_addresses':N,
           'max_exception_shifts':s,'check_rows_with_padding':S,
           'padding_rows_per_family':2},
    'scope':'Complete finite repair with physical comparison keys and both directions. Predictor uses direct diagonalizers, not succinct pencils. Phase1/16 checked separately; no full tape-machine/global bound verification.',
}
Path(__file__).with_name('compact-spectral-repair-verification.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps(result,indent=2))
