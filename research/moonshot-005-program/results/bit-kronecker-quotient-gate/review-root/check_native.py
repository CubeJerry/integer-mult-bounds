def echelon(words):
    out={}
    for w in words:
        while w:
            p=w.bit_length()-1
            if p in out:
                w ^= out[p]
            else:
                out[p]=w
                break
    return out

def residue(w,basis):
    for p in sorted(basis,reverse=True):
        if w>>p&1:
            w ^= basis[p]
    return w

def local_kernel_words(basis,allowed,universe):
    # Eliminate the forbidden restrictions while carrying original words.
    pivots={}
    null=[]
    for original in basis:
        forbidden=original & (universe ^ allowed)
        carried=original
        while forbidden:
            p=forbidden.bit_length()-1
            if p in pivots:
                old,full=pivots[p]
                forbidden ^= old
                carried ^= full
            else:
                pivots[p]=(forbidden,carried)
                break
        else:
            assert not carried & (universe ^ allowed)
            null.append(carried)
    return list(echelon(null).values())

