#!/usr/bin/env python3
"""Independent finite optimization of packet spans; no formula in optimizer."""
from __future__ import annotations

import argparse
import heapq
import json
from pathlib import Path


def canon(rows: tuple[int, ...] | list[int]) -> tuple[int, ...]:
    pivots: dict[int, int] = {}
    for value in rows:
        for p in sorted(pivots, reverse=True):
            if value >> p & 1:
                value ^= pivots[p]
        if not value:
            continue
        p = value.bit_length() - 1
        for q in list(pivots):
            if pivots[q] >> p & 1:
                pivots[q] ^= value
        pivots[p] = value
    return tuple(pivots[p] for p in sorted(pivots, reverse=True))


def contained(small: tuple[int, ...], large: tuple[int, ...]) -> bool:
    return len(canon(list(small + large))) == len(large)


def optimize(hdim: int, sizes: tuple[int, ...], prices: tuple[int, int, int]):
    total = hdim + sum(sizes)
    hmask = (1 << hdim) - 1
    masks = []
    at = hdim
    for size in sizes:
        masks.append(((1 << size) - 1) << at)
        at += size
    direct, upper, lower = prices
    packets: dict[int, int] = {}
    for v in range(1, 1 << total):
        hv = v & hmask
        held = v ^ hv
        if not held:
            packets[v] = min(direct, upper + lower)
        elif sum(bool(held & a) for a in masks) == 1:
            packets[v] = upper + lower if hv else lower
    best: dict[tuple[int, ...], int] = {(): 0}
    heap = [(0, ())]
    while heap:
        cost, space = heapq.heappop(heap)
        if best[space] != cost:
            continue
        for v, price in packets.items():
            nxt = canon(list(space) + [v])
            if len(nxt) == len(space):
                continue
            candidate = cost + price
            if candidate < best.get(nxt, 10**9):
                best[nxt] = candidate
                heapq.heappush(heap, (candidate, nxt))
    # All subspaces of the ambient space, including targets not generated by
    # admissible packets alone. Construct independently from every vector.
    all_spaces = {()}
    for v in range(1, 1 << total):
        all_spaces.update(canon(list(s) + [v]) for s in list(all_spaces))
    cases = []
    failures_nontransverse = []
    for target in sorted(all_spaces, key=lambda x: (len(x), x)):
        if not target:
            continue
        c = len(target)
        hub_rank = len(canon([v & hmask for v in target]))
        p = len(canon([v & ~hmask for v in target]))
        marginal = sum(len(canon([v & a for v in target])) for a in masks)
        actual = min(cost for s, cost in best.items() if contained(target, s))
        formula = (c - p) * direct + p * upper + marginal * lower
        record = {"target": list(target), "c": c, "p": p, "t": marginal,
                  "actual": actual, "formula": formula}
        if hub_rank == c:
            if not 0 < upper < direct <= upper + lower:
                continue
            if actual != formula:
                raise AssertionError(record)
            cases.append(record)
        elif actual < formula:
            failures_nontransverse.append(record)
    return {"ambient_dimension": total, "hub_dimension": hdim,
            "chart_dimensions": list(sizes), "prices": list(prices),
            "all_target_subspaces": len(all_spaces), "admissible_spans": len(best),
            "transverse_cases": len(cases),
            "nontransverse_strict_controls": len(failures_nontransverse),
            "one_nontransverse_control": next(iter(failures_nontransverse), None)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    reports = []
    for hdim, sizes in [(1, (1, 1)), (2, (1, 1)), (1, (2, 2)), (2, (1, 1, 1))]:
        for prices in [(8, 2, 6), (7, 2, 6), (7, 4, 4), (9, 7, 4)]:
            reports.append(optimize(hdim, sizes, prices))
    assert sum(x["nontransverse_strict_controls"] for x in reports) > 0
    # A lone Hub vector can take a zero-read two-segment route if concavity
    # is dropped, refuting the formula A under A>B+C.
    nonconcave = {"A": 10, "B": 2, "C": 6, "formula": 10, "actual": 8}
    assert nonconcave["actual"] < nonconcave["formula"]
    result = {"status": "PASS_EXACT_UNIFORM_CHART_MOVEMENT_OPTIMUM",
              "positive_cases": sum(x["transverse_cases"] for x in reports),
              "optimizations": reports, "nonconcave_control": nonconcave,
              "scope": "finite binary controls of universal written theorem; no new kappa"}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "RESULT.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({"status": result["status"], "cases": result["positive_cases"],
                      "optimizations": len(reports)}))


if __name__ == "__main__":
    main()
